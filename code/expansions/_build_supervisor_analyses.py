md(r"""## E1 — Min/max O-information as relative values

Absolute O magnitudes are confounded (subset size, activity, estimator bias), so lead with **relative**
quantities: per (arch, seed, k) the **range = max O − min O**, and the paired het−hom differences — **k ≤ 8
only** (the reliable regime). het's *range* is the defensible signal (breadth), not absolute O.

> **Bias caveat (from the literature check).** The plug-in O-information estimator is biased **toward synergy**
> (spuriously negative O) when samples are scarce, and the bias lands hardest on the **min-O (most
> synergistic)** tail — so min-O is the least trustworthy statistic. The reliable rule is `T ≫ 2^k` (binary);
> at k=8 with T≈512k, `T/2^k ≈ 2000`, comfortably safe, which is why we cap at k≤8. Because both het and hom
> are binary with the same T, the **paired het−hom** comparison cancels most of the shared bias — that
> relative readout is more robust than any absolute O. (Gelens et al. 2024; Rosas et al. 2019.)""")
code(r'''
# ========================== E1. Relative min/max O ==========================
recs = [json.loads(l) for l in open(OSREC)]
ok = [r for r in recs if r.get("status") == "ok"]
RK = [2, 4, 6, 8]                          # reliable regime only
def stat_at(a, k, which):
    out = []
    for s in SEEDS:
        v = [r["O_info"] for r in ok if r["arch"] == a and r["seed"] == s and r["k"] == k]
        if v: out.append({"min": min(v), "max": max(v), "range": max(v) - min(v)}[which])
    return np.array(out)

print("relative min/max-O (mean over seeds, k<=8):")
print(f"{'k':>3} | {'het range':>10} {'hom range':>10} | {'het minO':>9} {'hom minO':>9}")
band = {"het": {"m": [], "s": []}, "hom": {"m": [], "s": []}}
for k in RK:
    hr, orr = stat_at("het", k, "range"), stat_at("hom", k, "range")
    hm, om = stat_at("het", k, "min"), stat_at("hom", k, "min")
    for a, v in (("het", hr), ("hom", orr)): band[a]["m"].append(v.mean()); band[a]["s"].append(v.std())
    print(f"{k:>3} | {hr.mean():>10.3f} {orr.mean():>10.3f} | {hm.mean():>+9.3f} {om.mean():>+9.3f}")

print("\npaired het vs hom (permutation-tested):")
for k in (6, 8):
    print("  " + fmt_report(f"O range k={k}", stat_at("het", k, "range"), stat_at("hom", k, "range")))
    print("  " + fmt_report(f"O min   k={k}", stat_at("het", k, "min"), stat_at("hom", k, "min")))

fig, ax = plt.subplots(figsize=(7.5, 5))
for a in ("het", "hom"):
    m, s = np.array(band[a]["m"]), np.array(band[a]["s"])
    ax.plot(RK, m, color=COL[a], lw=2, marker="o", label=f"{a} O-range")
    ax.fill_between(RK, m - s, m + s, color=COL[a], alpha=0.18)
ax.set_xlabel("subset size k"); ax.set_ylabel("O-information range (max − min)")
ax.set_title("Relative min/max O: het spans a wider range (breadth)\n±1 std across seeds, reliable k≤8", fontweight="bold")
ax.grid(alpha=0.3); ax.legend()
plt.tight_layout(); plt.savefig(FIGDIR / "fig_minmax_o_relative.png", dpi=150, bbox_inches="tight"); plt.show()
print("saved ->", FIGDIR / "fig_minmax_o_relative.png")
''')

