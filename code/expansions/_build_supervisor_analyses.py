@torch.no_grad()
def hidden_spikes(model, prms, units, times, labels, n_batches=N_BATCHES, stride=1):
    nb_hidden = int(model.network[0].output_size); nb_steps = int(prms["nb_steps"]); nb_inputs = int(prms["nb_inputs"])
    bs = int(prms["batch_size"]); inv = 1.0 / float(prms["time_step"])
