def evr_from_matrix(X):
    """explained-variance-ratio (desc) of [samples x features] via covariance eigenvalues."""
    X = np.asarray(X, np.float64); X = X - X.mean(0, keepdims=True)
    if X.shape[0] < 2 or np.allclose(X, 0): return np.array([np.nan])
