md(r"""## D — Fourier analysis of the SHD inputs

Smooth the **test-set input** spike trains (Gaussian kernel), take the power spectrum, and convert frequency
to an integration timescale `τ ≈ 1/(2πf)`. This shows **which timescales the task carries** — the empirical
grounding for "task-aligned τ". Overlaid: the learned **het** τ spread and the **hom** τ (from the
checkpoints). If the input power spans the het range while sitting above the hom ~5 ms point, that is the
mechanism in one figure.""")
code(r'''
# ========================== D. Input Fourier ==========================
from math import pi
DT = 1e-3                      # 1 ms bins
SMOOTH_MS = 3.0                # Gaussian smoothing sigma (ms)
N_TRIALS_FFT = 400             # test trials to average over
NB_STEPS = 1000

def gaussian_kernel(sigma_ms, dt=DT):
    sig = sigma_ms * 1e-3 / dt; r = int(4*sig); xk = np.arange(-r, r+1)
    k = np.exp(-0.5*(xk/sig)**2); return k / k.sum()

def input_rate_matrix(units, times, n_trials=N_TRIALS_FFT):
    """[n_trials, NB_STEPS, 700] smoothed input rates for the first n_trials test samples."""
    ker = gaussian_kernel(SMOOTH_MS)
    idx = np.arange(min(n_trials, len(units)))
    M = np.zeros((len(idx), NB_STEPS, 700), np.float32)
    for j, i in enumerate(idx):
        t = np.round(np.asarray(times[i]) / DT).astype(int); u = np.asarray(units[i])
        v = (t >= 0) & (t < NB_STEPS); t, u = t[v], u[v]
        np.add.at(M[j], (t, u), 1.0)
    # smooth along time
    M = np.apply_along_axis(lambda m: np.convolve(m, ker, mode="same"), 1, M)
    return M

Xin = input_rate_matrix(UN, TI)
# power spectrum: FFT over time per (trial, channel), average power
F = np.fft.rfft(Xin - Xin.mean(1, keepdims=True), axis=1)
psd = (np.abs(F)**2).mean(axis=(0, 2))                       # avg over trials & channels
freqs = np.fft.rfftfreq(NB_STEPS, d=DT)
psd[0] = 0.0

# learned tau (ms) from checkpoints
def tau_ms_of(path, layer=0):
    ck = torch.load(path, map_location="cpu", weights_only=False)
    b = ck["model_state_dict"][f"network.{layer}.beta"].numpy().ravel()
    return src.decay_to_tau_ms(b, DT)
het_tau = np.concatenate([tau_ms_of(CKPTS / HET_F.format(s=s)) for s in SEEDS])
hom_tau = np.concatenate([tau_ms_of(CKPTS / HOM_F.format(s=s)) for s in SEEDS])

fig, ax = plt.subplots(1, 2, figsize=(14, 5))
pos = freqs > 0
ax[0].semilogx(freqs[pos], psd[pos] / psd[pos].max(), color="k", lw=2)
ax[0].set_xlabel("frequency (Hz)"); ax[0].set_ylabel("normalised power")
ax[0].set_title(f"SHD input power spectrum (test, {SMOOTH_MS:.0f} ms smoothing)", fontweight="bold"); ax[0].grid(alpha=0.3, which="both")
# same power vs timescale tau = 1/(2 pi f), with the learned tau distributions overlaid
tau_axis = 1e3 / (2*pi*freqs[pos])       # ms
ax[1].semilogx(tau_axis, psd[pos] / psd[pos].max(), color="k", lw=2, label="input power")
ax[1].hist(het_tau, bins=np.logspace(np.log10(2), np.log10(220), 30), density=True, alpha=0.4, color=COL["het"], label="het learned τ")
ax[1].axvline(np.median(hom_tau), color=COL["hom"], lw=2, ls="--", label=f"hom τ (median {np.median(hom_tau):.1f} ms)")
ax[1].set_xlabel("integration timescale τ = 1/(2πf)  (ms)"); ax[1].set_ylabel("normalised (power / density)")
ax[1].set_title("Task timescales vs learned τ", fontweight="bold"); ax[1].grid(alpha=0.3, which="both"); ax[1].legend(fontsize=8)
plt.tight_layout(); plt.savefig(FIGDIR / "fig_input_fourier.png", dpi=150, bbox_inches="tight"); plt.show()
# peak / spectral centroid
centroid = float((freqs[pos] * psd[pos]).sum() / psd[pos].sum())
print(f"spectral centroid ≈ {centroid:.1f} Hz  (τ ≈ {1e3/(2*pi*centroid):.1f} ms)")
print(f"het learned τ: median {np.median(het_tau):.1f} ms, range [{het_tau.min():.1f}, {het_tau.max():.1f}]")
print(f"hom learned τ: median {np.median(hom_tau):.1f} ms")
print("saved ->", FIGDIR / "fig_input_fourier.png")
''')

